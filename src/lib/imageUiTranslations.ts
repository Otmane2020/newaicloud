export function getImageUiTranslations(language?: string) {
  return language === 'fr' ? fr : en;
}

export function translateImageGenerationError(error: unknown, language?: string): string {
  const ui = getImageUiTranslations(language);
  const raw = error instanceof Error ? error.message : String(error ?? '');
  const normalized = raw.toUpperCase();

  if (normalized.includes('LIMIT_REACHED') || normalized.includes('429')) return ui.errors.limitReached;
  if (normalized.includes('ALL_PROVIDERS_FAILED')) return ui.errors.providersFailed;
  if (normalized.includes('IMAGEURL IS REQUIRED') || normalized.includes('IMAGE_URL_REQUIRED')) return ui.errors.missingImage;
  if (normalized.includes('JWT') || normalized.includes('UNAUTHORIZED') || normalized.includes('AUTH')) return ui.errors.authentication;
  if (normalized.includes('NO_AI_IMAGE_PROVIDER') || normalized.includes('NO PROVIDER')) return ui.errors.missingProvider;
  if (normalized.includes('EDGE FUNCTION RETURNED A NON-2XX')) return ui.errors.genericGeneration;

  return raw || ui.errors.genericGeneration;
}
